"""Snapshot Wiktionary/Kaikki entries for reliable initial and offline lookups."""
import urllib.request,json,pathlib,urllib.parse
from concurrent.futures import ThreadPoolExecutor
ROOT=pathlib.Path(__file__).resolve().parents[1];CACHE=pathlib.Path('/tmp/leesmaat-source-cache')
OUT=ROOT/'public/dictionaries';OUT.mkdir(exist_ok=True)

def get(url):return urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':'Leesmaat/1.0 (https://github.com/thembaxx/leesmaat)'}),timeout=40).read()
def compact(records,language):
 word=records[0]['word']; mean=[];phon=[];forms=[]
 for record in records:
  pos=record.get('pos','').replace('adj','adjective').replace('adv','adverb')
  senses=[]
  for sense in record.get('senses',[]):
   glosses=sense.get('glosses',[])
   if not glosses:continue
   examples=[e.get('text','') for e in sense.get('examples',[]) if e.get('text')][:1]
   senses.append({'definition':glosses[-1],'example':examples[0][:400] if examples else None,'synonyms':[s['word'] for s in sense.get('synonyms',[]) if s.get('word')][:8],'lemma':sense.get('form_of',[{}])[0].get('word')})
  if senses:mean.append({'partOfSpeech':pos,'definitions':senses[:8]})
  for sound in record.get('sounds',[]):
   if sound.get('ipa'):phon.append({'text':sound['ipa'],'label':', '.join(sound.get('tags',[]))})
  forms.extend(f['form'] for f in record.get('forms',[]) if f.get('form') and f['form']!='-')
 return {'word':word,'language':language,'phonetics':phon[:5],'meanings':mean,'forms':list(dict.fromkeys(forms))[:30],'source':'https://en.wiktionary.org/wiki/'+urllib.parse.quote(word)+'#'+('Afrikaans' if language=='af' else 'English'),'provider':'Wiktionary via Kaikki','licence':'CC BY-SA 4.0 / GFDL','licenceUrl':'https://creativecommons.org/licenses/by-sa/4.0/'}

afp=CACHE/'afrikaans-dictionary.jsonl'
if not afp.exists():afp.write_bytes(get('https://kaikki.org/dictionary/Afrikaans/kaikki.org-dictionary-Afrikaans.jsonl'))
groups={}
for line in afp.read_text().splitlines():
 r=json.loads(line);groups.setdefault(r['word'],[]).append(r)
af={w.casefold():compact(records,'af') for w,records in groups.items() if any(r.get('senses') for r in records)}
(OUT/'af.json').write_text(json.dumps(af,ensure_ascii=False,separators=(',',':'))+'\n')
print('Afrikaans entries:',len(af),flush=True)
english=['reading','read','book','story','poem','article','light','flicker','flickered','neighbour','understood','linger','borrow','habit','comprehension','vocabulary','negotiate','horizon','quiet','garden','portrait','beautiful','lawyer','street','curious','rabbit','treasure','island','confidence','interpretation','evidence','repetition','patience','mist','candle','mountain','language','memory','friendship','honest','adventure']

def word(w):
 p=CACHE/f'dict-en-{w}.jsonl'
 try:
  if not p.exists():p.write_bytes(get('https://kaikki.org/dictionary/English/meaning/'+urllib.parse.quote(w[:1])+'/'+urllib.parse.quote(w[:2])+'/'+urllib.parse.quote(w)+'.jsonl'))
  result=compact([json.loads(l) for l in p.read_text().splitlines() if l.strip()],'en')
  return w,result
 except Exception as e:print(w,str(e),flush=True);return w,None
seed={w:v for w,v in ThreadPoolExecutor(2).map(word,english) if v}
for w in ['perron','verskyn','geglimlag','ontwaak','stilte','vlakte','heuwel','boek','lees','tuin','gedig','woord','storie']:
 if w in af:seed['af:'+w]=af[w]
(ROOT/'src/lib/dictionary-seed.json').write_text(json.dumps(seed,ensure_ascii=False,indent=2)+'\n')
(OUT/'SOURCE.md').write_text('Definitions and pronunciation: Wiktionary contributors, extracted by Kaikki / Wiktextract. Source: https://kaikki.org/dictionary/\nLicence: CC BY-SA 4.0 and GFDL; per-entry source and licence links are retained.\nAfrikaans lemmas have English glosses, from the English Wiktionary edition. Definitions are not generated by Leesmaat.\n')
print('Seed entries:',len(seed),flush=True)
